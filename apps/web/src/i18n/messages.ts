export type MessageKey = keyof (typeof messages)[typeof defaultLocale];
export type MessageParams = Record<string, string | number>;

export function translate(
  locale: Locale,
  key: MessageKey,
  params: MessageParams = {},
): string {
  const dictionary = messages[locale] ?? messages[defaultLocale];
  const template = dictionary[key] ?? messages[defaultLocale][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, paramKey) =>
    Object.prototype.hasOwnProperty.call(params, paramKey)
      ? String(params[paramKey])
      : match,
  );
}

export function formatLocaleDate(
  locale: Locale,
  value: Date | string | number,
) {
  return new Intl.DateTimeFormat(locale, { dateStyle: "short" }).format(
    new Date(value),
  );
}
